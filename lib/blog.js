export const blogPosts = articles.map((article) => {
  const bodyText = [article.lead, ...article.takeaways, ...article.sections.flatMap((section) => [section.title, ...(section.paragraphs || []), ...(section.list || []), ...(section.paragraphsAfter || []), section.callout || '', ...(section.table?.headers || []), ...(section.table?.rows || []).flat()]), ...article.faq.flat()].join(' ');
  const wordCount = bodyText.trim().split(/\s+/u).length;
  return {
    ...article,
    datePublished: published,
    dateModified: published,
    author: site.profileName,
    wordCount,
    readingMinutes: Math.max(3, Math.ceil(wordCount / 150)),
    image: { src: `/images/blog-${article.slug}.webp`, alt: article.imageAlt, width: 1672, height: 941 }
  };
});

